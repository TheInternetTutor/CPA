#!/usr/bin/env bash
set -euo pipefail

INPUT_NORMALIZED=${1:?usage: risk_behavior.sh NORMALIZED.jsonl MATCHES.jsonl OUTPUT_DIR}
INPUT_MATCHES=${2:?usage: risk_behavior.sh NORMALIZED.jsonl MATCHES.jsonl OUTPUT_DIR}
OUTPUT_DIR=${3:-.}

command -v jq >/dev/null || { echo 'error: jq is required' >&2; exit 1; }
mkdir -p "$OUTPUT_DIR"

OUTPUT="$OUTPUT_DIR/risk_behavior.json"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# ----------------------------------------------------------------------
# Fragment-level streaks and extremes.
# ----------------------------------------------------------------------
jq -s '
  def streaks:
    reduce .[] as $r
      ({win:0,loss:0,max_win:0,max_loss:0};
       if $r.realized_pnl > 0 then
         .win += 1 | .loss = 0 | .max_win = ([.max_win,.win]|max)
       elif $r.realized_pnl < 0 then
         .loss += 1 | .win = 0 | .max_loss = ([.max_loss,.loss]|max)
       else .win = 0 | .loss = 0
       end);
  . as $rows
  | (streaks) as $s
  | {
      max_winning_fifo_fragment_streak: $s.max_win,
      max_losing_fifo_fragment_streak: $s.max_loss,
      largest_winning_fragment: ($rows | map(select(.realized_pnl > 0)) | max_by(.realized_pnl)),
      largest_losing_fragment: ($rows | map(select(.realized_pnl < 0)) | min_by(.realized_pnl))
    }
' "$INPUT_MATCHES" > "$TMP/fragments.json"

# ----------------------------------------------------------------------
# Daily streaks, best/worst days, and drawdown/recovery episodes.
# Daily input is generated by performance_metrics.sh.
# ----------------------------------------------------------------------
jq -s '
  def day_seconds($d): ($d + "T00:00:00Z" | fromdateiso8601);
  def streaks:
    reduce .[] as $r
      ({win:0,loss:0,max_win:0,max_loss:0};
       if $r.realized_pnl > 0 then
         .win += 1 | .loss = 0 | .max_win = ([.max_win,.win]|max)
       elif $r.realized_pnl < 0 then
         .loss += 1 | .win = 0 | .max_loss = ([.max_loss,.loss]|max)
       else .win = 0 | .loss = 0
       end);
  def drawdowns:
    reduce .[] as $r
      ({episodes:[], current:null, prev:null};
       if $r.drawdown < -0.0000001 then
         if .current == null then
           .current = {start:$r.date, trough_date:$r.date, trough:$r.drawdown}
         else
           .current.trough = ([.current.trough,$r.drawdown]|min)
           | if $r.drawdown == .current.trough then .current.trough_date=$r.date else . end
         end
       elif .current != null then
         .current.recovery_date = $r.date
         | .current.recovery_days = ((day_seconds($r.date)-day_seconds(.current.start))/86400)
         | .episodes += [.current]
         | .current = null
       else .
       end
       | .prev = $r.date
      )
    | if .current != null then .episodes += [.current] else . end
    | .episodes;
  . as $rows
  | (streaks) as $s
  | (drawdowns) as $dd
  | {
      max_winning_day_streak: $s.max_win,
      max_losing_day_streak: $s.max_loss,
      best_day: ($rows | map(select(.realized_pnl != 0)) | max_by(.realized_pnl)),
      worst_day: ($rows | map(select(.realized_pnl != 0)) | min_by(.realized_pnl)),
      drawdown_summary: {
        number_of_drawdown_episodes: ($dd|length),
        maximum_drawdown: ($rows|map(.drawdown)|min),
        maximum_drawdown_episode: (if ($dd|length)>0 then ($dd|min_by(.trough)) else null end),
        longest_recovery_days: (if ($dd|map(select(.recovery_days != null))|length)>0 then ($dd|map(select(.recovery_days != null)|.recovery_days)|max) else null end),
        average_recovery_days: (if ($dd|map(select(.recovery_days != null))|length)>0 then ($dd|map(select(.recovery_days != null)|.recovery_days)|add / length) else null end),
        unrecovered_drawdowns: ($dd|map(select(.recovery_days == null))|length)
      }
    }
' daily_performance.jsonl > "$TMP/daily.json"

# ----------------------------------------------------------------------
# Monthly consistency and best/worst months.
# ----------------------------------------------------------------------
jq -s '
  . as $rows
  | {
      active_months: ($rows|length),
      profitable_months: ($rows|map(select(.realized_pnl>0))|length),
      losing_months: ($rows|map(select(.realized_pnl<0))|length),
      profitable_month_percentage: (if ($rows|length)>0 then (($rows|map(select(.realized_pnl>0))|length) / ($rows|length) * 100) else null end),
      best_month: ($rows|max_by(.realized_pnl)),
      worst_month: ($rows|min_by(.realized_pnl)),
      positive_month_pnl: ($rows|map(select(.realized_pnl>0)|.realized_pnl)|add // 0),
      negative_month_pnl: ($rows|map(select(.realized_pnl<0)|.realized_pnl)|add // 0)
    }
' monthly_performance.jsonl > "$TMP/monthly.json"

# ----------------------------------------------------------------------
# Symbol concentration. Net symbol P&L comes from the canonical symbol
# attribution; gross gains/losses are computed directly from FIFO fragments.
# ----------------------------------------------------------------------
jq -s '
  group_by(.symbol)
  | map({
      symbol: .[0].symbol,
      realized_pnl: (map(.realized_pnl)|add),
      gross_profit: (map(select(.realized_pnl>0)|.realized_pnl)|add // 0),
      gross_loss: (map(select(.realized_pnl<0)|.realized_pnl)|add // 0),
      fifo_fragments: length,
      wins: (map(select(.realized_pnl>0))|length),
      losses: (map(select(.realized_pnl<0))|length)
    })
' "$INPUT_MATCHES" > "$TMP/symbols.json"

jq '
  def positive: map(select(.realized_pnl>0));
  def negative: map(select(.realized_pnl<0));
  . as $rows
  | ($rows|map(.gross_profit)|add // 0) as $gp
  | ($rows|map(.gross_loss)|add // 0) as $gl
  | {
      symbols_with_realized_pnl: ($rows|length),
      positive_contributor_symbols: ($rows|positive|length),
      detractor_symbols: ($rows|negative|length),
      gross_profit: $gp,
      gross_loss: $gl,
      top_5_symbols_by_realized_pnl: ($rows|sort_by(-.realized_pnl)|.[0:5]),
      top_10_symbols_by_realized_pnl: ($rows|sort_by(-.realized_pnl)|.[0:10]),
      top_5_positive_share_of_gross_profit_pct: (if $gp>0 then (($rows|sort_by(-.gross_profit)|.[0:5]|map(.gross_profit)|add) / $gp * 100) else null end),
      top_10_positive_share_of_gross_profit_pct: (if $gp>0 then (($rows|sort_by(-.gross_profit)|.[0:10]|map(.gross_profit)|add) / $gp * 100) else null end),
      top_5_detractors_share_of_gross_loss_pct: (if $gl<0 then (($rows|sort_by(.gross_loss)|.[0:5]|map(.gross_loss|abs)|add) / ($gl|abs) * 100) else null end),
      top_10_detractors_share_of_gross_loss_pct: (if $gl<0 then (($rows|sort_by(.gross_loss)|.[0:10]|map(.gross_loss|abs)|add) / ($gl|abs) * 100) else null end)
    }
' "$TMP/symbols.json" > "$TMP/symbols_summary.json"

# ----------------------------------------------------------------------
# Monthly trading-frequency evolution from actual completed stock orders.
# ----------------------------------------------------------------------
jq -s '
  map(select(.analysis_class == "STOCK_BUY_COMPLETED" or .analysis_class == "STOCK_SELL_COMPLETED")
      | .period = .date[0:7])
  | group_by(.period)
  | map({
      period: .[0].period,
      completed_buys: (map(select(.analysis_class=="STOCK_BUY_COMPLETED"))|length),
      completed_sells: (map(select(.analysis_class=="STOCK_SELL_COMPLETED"))|length),
      completed_stock_orders: length,
      symbols_traded: (map(.asset_type)|unique|length)
    })
' "$INPUT_NORMALIZED" > "$TMP/frequency.json"

export INPUT_NORMALIZED INPUT_MATCHES

# ----------------------------------------------------------------------
# Assemble one auditable JSON document.
# ----------------------------------------------------------------------
jq -n \
  --slurpfile fragment "$TMP/fragments.json" \
  --slurpfile daily "$TMP/daily.json" \
  --slurpfile monthly "$TMP/monthly.json" \
  --slurpfile symbols "$TMP/symbols_summary.json" \
  --slurpfile frequency "$TMP/frequency.json" \
  '{
    analysis_scope: "realized FIFO trading results only",
    source_files: {
      normalized_transactions: $ENV.INPUT_NORMALIZED,
      fifo_matches: $ENV.INPUT_MATCHES,
      daily_performance: "daily_performance.jsonl",
      monthly_performance: "monthly_performance.jsonl",
      symbol_attribution: "symbol_attribution.json"
    },
    streaks_and_extremes: $fragment[0],
    daily_behavior: $daily[0],
    monthly_consistency: $monthly[0],
    symbol_concentration: $symbols[0],
    trading_frequency_by_month: $frequency
  }' > "$OUTPUT"

jq -e . "$OUTPUT" >/dev/null
printf 'Wrote %s\n' "$OUTPUT"
